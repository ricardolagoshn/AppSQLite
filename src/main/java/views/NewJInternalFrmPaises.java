    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();

        if(nombre.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "El nombre del pais es obligatorio");
            txtNombre.requestFocus();
            return;
        }

        if(existeNombre(nombre, 0))
        {
            JOptionPane.showMessageDialog(this, "Ya existe un pais con ese nombre");
            txtNombre.requestFocus();
            return;
        }

        Pais pais = new Pais();
        pais.setNombre(nombre);
        pais.setEstado(chkActivo.isSelected());

        dao.insertar(pais);

        JOptionPane.showMessageDialog(this, "Pais guardado con exito");

        limpiar();
        cargarPaises();
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if(txtIdPais.getText().isBlank())
        {
            JOptionPane.showMessageDialog(this, "Seleccione un pais de la tabla");
            return;
        }

        int idPais = Integer.parseInt(txtIdPais.getText());
        String nombre = txtNombre.getText().trim();

        if(nombre.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "El nombre del pais es obligatorio");
            txtNombre.requestFocus();
            return;
        }

        if(existeNombre(nombre, idPais))
        {
            JOptionPane.showMessageDialog(this, "Ya existe otro pais con ese nombre");
            txtNombre.requestFocus();
            return;
        }

        Pais pais = new Pais(idPais, nombre, chkActivo.isSelected());
        dao.actualizar(pais);

        JOptionPane.showMessageDialog(this, "Pais actualizado con exito");

        cargarPaises();
        limpiar();
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if(txtIdPais.getText().isBlank())
        {
            JOptionPane.showMessageDialog(this, "Seleccione un pais de la tabla");
            return;
        }

        int idPais = Integer.parseInt(txtIdPais.getText());

        int respuesta = JOptionPane.showConfirmDialog(this,
                "Desea eliminar el pais " + txtNombre.getText() + " ?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION);

        if(respuesta == JOptionPane.YES_OPTION)
        {
            dao.eliminar(idPais);
            cargarPaises();
            limpiar();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tbPaisesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbPaisesMouseClicked
        int fila = tbPaises.getSelectedRow();

        if(fila >= 0)
        {
            int filaModelo = tbPaises.convertRowIndexToModel(fila);
            int idPais = (int) tbPaises.getModel().getValueAt(filaModelo, 0);

            Pais pais = dao.buscarPorId(idPais);
            if(pais != null)
            {
                txtIdPais.setText(String.valueOf(pais.getIdPais()));
                txtNombre.setText(pais.getNombre());
                chkActivo.setSelected(pais.isEstado());
                txtFechaRegistro.setText(pais.getFechaRegistro());

                btnGuardar.setEnabled(false);
                btnActualizar.setEnabled(true);
                btnEliminar.setEnabled(true);
            }
        }
    }//GEN-LAST:event_tbPaisesMouseClicked


