    private void cargarPaises()
    {
        DefaultTableModel tbmodelo = new DefaultTableModel(new Object[]{"ID","NOMBRE","ESTADO","FECHA REGISTRO"},0)
        {
            @Override
            public boolean isCellEditable(int fila, int columna)
            {
                return false;
            }
        };

        for(Pais p : dao.listar())
        {
            tbmodelo.addRow(new Object[]
            {
                p.getIdPais(),
                p.getNombre(),
                p.isEstado() ? "Activo" : "Inactivo",
                p.getFechaRegistro()
            });
        }

        tbPaises.setModel(tbmodelo);
    }

    // Verifica si ya existe un pais con el mismo nombre (ignorando el id indicado)
    private boolean existeNombre(String nombre, int idIgnorar)
    {
        for(Pais p : dao.listar())
        {
            if(p.getIdPais() != idIgnorar && p.getNombre().equalsIgnoreCase(nombre))
            {
                return true;
            }
        }
        return false;
    }

    private void limpiar()
    {
        txtIdPais.setText("");
        txtNombre.setText("");
        chkActivo.setSelected(true);
        txtFechaRegistro.setText("");
        tbPaises.clearSelection();

        btnGuardar.setEnabled(true);
        btnActualizar.setEnabled(false);
        btnEliminar.setEnabled(false);

        txtNombre.requestFocus();
    }
